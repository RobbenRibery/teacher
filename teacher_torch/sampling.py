from __future__ import annotations

from dataclasses import dataclass
from typing import Optional
import torch
from transformers import (
    PreTrainedModel,
    PreTrainedTokenizer,
    GenerationConfig,
    set_seed,
)
from teacher_torch.utils import setup_logger_with_file_line

logger = setup_logger_with_file_line(__name__)


def get_eos_token_ids(
    tokenizer: PreTrainedTokenizer,
    extra_stop_strings: Optional[list[str]] = None,
) -> list[int]:
    """Get list of EOS token IDs including tokenized stop strings.
    
    Args:
        tokenizer: The tokenizer to use for encoding stop strings.
        extra_stop_strings: Optional list of strings that should also trigger EOS.
            These strings will be tokenized and their token IDs added to the EOS list.
    
    Returns:
        List of token IDs that should trigger end of generation.
    """
    eos_ids: list[int] = []
    
    # Add default EOS token(s)
    if tokenizer.eos_token_id is not None:
        if isinstance(tokenizer.eos_token_id, list):
            eos_ids.extend(tokenizer.eos_token_id)
        else:
            eos_ids.append(tokenizer.eos_token_id)
    
    # Add tokenized stop strings
    if extra_stop_strings:
        for stop_str in extra_stop_strings:
            # Tokenize without special tokens to get just the string's tokens
            token_ids = tokenizer.encode(stop_str, add_special_tokens=False)
            if token_ids:
                # Use the last token as the stopping token (handles multi-token strings)
                # This ensures we stop when we've generated the complete stop string
                eos_ids.append(token_ids[-1])
                logger.info(f"Added stop string '{stop_str}' -> token ID {token_ids[-1]} (full: {[tokenizer.decode(token_id) for token_id in token_ids]})")
    
    # Remove duplicates while preserving order
    seen = set()
    unique_eos_ids = []
    for tid in eos_ids:
        if tid not in seen:
            seen.add(tid)
            unique_eos_ids.append(tid)
    
    return unique_eos_ids

@dataclass
class SamplingOutput:
    """Container for language model generation outputs.

    Stores all data produced by sampling responses from a Hugging Face language model,
    including tokenized inputs, generated sequences, masks, and decoded text. This output
    is typically used for reinforcement learning training pipelines (e.g., GRPO) where
    you need to distinguish between prompt tokens and generated tokens.

    Attributes:
        num_samples: Number of samples generated (batch size).
            Shape: scalar
        input_ids: Token IDs of the input prompts (before generation).
            Shape: (batch_size, prompt_seq_len)
        attention_mask: Attention mask for the input prompts, indicating which tokens
            are real (1) vs padding (0).
            Shape: (batch_size, prompt_seq_len)
        sequence_ids: Token IDs of the full sequences (prompt + generated completion).
            Shape: (batch_size, total_seq_len)
        action_mask: Boolean mask indicating which tokens were generated by the model.
            True for generated tokens, False for input prompt tokens and padding tokens.
            Note: This mask is aligned with log probabilities and has shape (seq_len - 1)
            since it marks transitions between tokens.
            Shape: (batch_size, total_seq_len - 1)
        completions: List of decoded completion strings (generated text only, excluding prompts).
            Length: batch_size
        prompts: List of original prompt strings used for generation.
            Length: batch_size
    """

    num_samples: int
    input_ids: torch.IntTensor
    sequence_attention_mask: (
        torch.IntTensor
    )  # this is the attention mask for the sequence ids
    sequence_ids: torch.IntTensor
    action_mask: torch.BoolTensor
    completions: list[str]
    prompts: list[str]
    group_size: int

    def __str__(self) -> str:
        return (
            f"SamplingOutput(\n"
            f"  num_samples: {self.num_samples}\n"
            f"  input_ids: shape={tuple(self.input_ids.shape)}, dtype={self.input_ids.dtype}\n"
            f"  sequence_attention_mask: shape={tuple(self.sequence_attention_mask.shape)}, dtype={self.sequence_attention_mask.dtype}\n"
            f"  sequence_ids: shape={tuple(self.sequence_ids.shape)}, dtype={self.sequence_ids.dtype}\n"
            f"  action_mask: shape={tuple(self.action_mask.shape)}, dtype={self.action_mask.dtype}\n"
            f"  completions: list[str], len={len(self.completions)}\n"
            f"  prompts: list[str], len={len(self.prompts)}\n"
            f"  group_size: {self.group_size}\n"
            f")"
        )


@torch.inference_mode()
def sample_responses_hf(
    model: PreTrainedModel,
    tokenizer: PreTrainedTokenizer,
    prompts: list[str],
    generation_config: GenerationConfig,
    seed: int = 42,
) -> SamplingOutput:
    """
    Sample responses from a Hugging Face language model for given prompts.

    This function generates text completions for a batch of prompts using the specified
    model and generation configuration. It sets a random seed for reproducibility and
    creates an action mask to identify generated tokens (excluding padding).

    Args:
        model: The pre-trained Hugging Face model to use for generation.
        tokenizer: The tokenizer associated with the model.
        prompts: List of prompt strings to generate completions for.
        generation_config: Generation configuration specifying parameters like
            max_length, temperature, top_p, etc.
        seed: Random seed for reproducibility. Defaults to 42.

    Returns:
        SamplingOutput: A dataclass containing:
            - num_samples: Number of samples generated (batch size).
            - input_ids: Token IDs of the input prompts.
            - sequence_ids: Token IDs of the full sequences (prompt + generated).
            - action_mask: Boolean mask indicating which tokens were generated
              (True for generated tokens, False for input/padding tokens).
            - completions: List of decoded completion strings.
    """
    assert tokenizer.padding_side == "left", (
        f"Tokenizer padding_side must be 'left', got '{tokenizer.padding_side}'"
    )
    model.eval()
    set_seed(seed)

    batch_inputs: dict[str, torch.IntTensor] = tokenizer(
        prompts,
        return_tensors="pt",
        padding=True,
        truncation=True,
        return_attention_mask=True,
        padding_side="left",
    )
    pad_token_id = tokenizer.pad_token_id
    prompt_len = batch_inputs["input_ids"].shape[1]

    logger.info(f"Generation config:\n======\n{generation_config.to_dict()}\n======\n")
    
    # Extract stop_strings and convert to eos_token_ids
    gen_kwargs = generation_config.to_dict()
    stop_strings = gen_kwargs.pop("stop_strings", None)
    
    # Build eos_token_ids list with any extra stop strings
    eos_token_ids = get_eos_token_ids(tokenizer, stop_strings)
    if eos_token_ids:
        gen_kwargs["eos_token_id"] = eos_token_ids
        logger.info(f"Using eos_token_ids: {eos_token_ids}")

    sequence_ids: torch.IntTensor = model.generate(
        input_ids=batch_inputs["input_ids"].to(model.device),
        attention_mask=batch_inputs["attention_mask"].to(model.device),
        **gen_kwargs,
    )

    action_mask: torch.BoolTensor = torch.zeros_like(
        sequence_ids, dtype=torch.bool, device=sequence_ids.device
    )
    action_mask[:, batch_inputs["input_ids"].shape[1] :] = True
    action_mask[sequence_ids == pad_token_id] = False
    action_mask: torch.BoolTensor = action_mask[:, 1:]

    sequence_attention_mask: torch.IntTensor = (sequence_ids != pad_token_id).long()

    return SamplingOutput(
        num_samples=sequence_ids.shape[0],
        input_ids=batch_inputs["input_ids"],
        sequence_attention_mask=sequence_attention_mask,
        sequence_ids=sequence_ids,
        action_mask=action_mask,
        completions=tokenizer.batch_decode(
            sequence_ids[:, batch_inputs["input_ids"].shape[1] :],
            skip_special_tokens=True,
        ),
        prompts=prompts,
        group_size=generation_config.num_return_sequences,
    )
