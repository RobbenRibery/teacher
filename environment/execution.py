import re
import traceback
from typing import Any, Optional
from pydantic import BaseModel, Field

class AnswerVerification(BaseModel):
    """
    Model for verification results.
    """
    correct: bool = Field(..., description="Whether the answer is correct according to the curriculum.")
    error: Optional[str] = Field(None, description="Traceback if the execution failed.")

def verify_answer(curriculum: str, variable_assignment: Any, variable_name: str = "x") -> AnswerVerification:
    """
    Validate that the curriculum is runnable by assigning variable name to a particular value.
    The curriculum should define a list of constraints (lambdas), e.g.:
    constraints = [lambda x: x > 0, lambda x: x < 10]
    
    Args:
        curriculum: Python code string defining a 'constraints' list of callables.
        variable_assignment: The value to test against the curriculum.
        variable_name: (Deprecated/Unused) The name of the variable.
        
    Returns:
        AnswerVerification object with correct=True/False and error details if any.
    """
    try:
        local_scope = {}
        
        # Execute the curriculum code to define constraints
        exec(curriculum, {}, local_scope)
        
        constraints = local_scope.get("constraints")
        
        if not isinstance(constraints, list):
            return AnswerVerification(correct=False, error="Curriculum must define a 'constraints' list.")
            
        for constraint in constraints:
            try:
                if not constraint(variable_assignment):
                    return AnswerVerification(correct=False, error=None)
            except Exception:
                return AnswerVerification(correct=False, error=traceback.format_exc())
        
        return AnswerVerification(correct=True, error=None)
        
    except Exception:
        return AnswerVerification(correct=False, error=traceback.format_exc())

def extract_format(text: str, regex_format: str, use_last_match: bool = True) -> Optional[str]:
    """
    Extract answer from solver generation using regex.
    
    Args:
        text: Text generated by the LLM.
        regex_format: Regex pattern to match the answer.
        use_last_match: Whether to use the last match or the first match. If set to True, the last match is returned.
                        If set to False or other values, the first match is returned.
    Returns:
        The matched string if found, otherwise None.
    """
    matches = list(re.finditer(regex_format, text, re.DOTALL))
    if matches and use_last_match:
        return matches[-1].group(0)
    elif matches:
        return matches[0].group(0)
    return None

def execute_answer(extracted_answer: str, variable_name: str = "x") -> Any:
    """
    Execute the extracted answer code to get the variable value.
    
    Args:
        extracted_answer: Python code to execute.
        variable_name: The name of the variable to extract after execution.
        
    Returns:
        The value of the variable from the execution scope.
    """
    local_scope = {}
    
    # Execute the code
    exec(extracted_answer, {}, local_scope)
    
    # Return the variable value if it exists
    if variable_name in local_scope:
        return local_scope[variable_name]
    
    return None

