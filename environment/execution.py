import re
import traceback
from typing import Any, Optional
from pydantic import BaseModel, Field

class AnswerVerification(BaseModel):
    """
    Model for verification results.
    """
    correct: bool = Field(..., description="Whether the answer is correct according to the curriculum.")
    error: Optional[str] = Field(None, description="Traceback if the execution failed.")

def verify_answer(curriculum: str, variable_assignment: Any, variable_name: str = "x") -> AnswerVerification:
    """
    Validate that the curriculum is runnable by assigning variable name to a particular value.
    The curriculum is constructed to return 0 if x is assigned to a wrong value, otherwise 1.
    
    Args:
        curriculum: The boolean constraints string (evaluatable python expression).
        variable_assignment: The value to test against the curriculum.
        variable_name: The name of the variable in the curriculum string.
        
    Returns:
        AnswerVerification object with correct=True/False and error details if any.
    """
    try:
        # Create context with the variable assignment
        context = {variable_name: variable_assignment}
        
        # Evaluate the curriculum expression
        # We use eval() assuming curriculum is an expression like "(x > 0) and (x < 10)"
        result = eval(curriculum, {}, context)
        
        # Check if result is truthy (1 or True)
        is_correct = bool(result)
        
        return AnswerVerification(correct=is_correct, error=None)
        
    except Exception:
        return AnswerVerification(correct=False, error=traceback.format_exc())

def extract_answer(solver_generation: str, regex_format: str) -> Optional[str]:
    """
    Extract answer from solver generation using regex.
    
    Args:
        solver_generation: Text generated by the LLM.
        regex_format: Regex pattern to match the answer.
        
    Returns:
        The matched string if found, otherwise None.
    """
    match = re.search(regex_format, solver_generation, re.DOTALL)
    if match:
        return match.group(0)
    return None

def execute_answer(extracted_answer: str, variable_name: str = "x") -> Any:
    """
    Execute the extracted answer code to get the variable value.
    
    Args:
        extracted_answer: Python code to execute.
        variable_name: The name of the variable to extract after execution.
        
    Returns:
        The value of the variable from the execution scope.
    """
    local_scope = {}
    
    # Execute the code
    exec(extracted_answer, {}, local_scope)
    
    # Return the variable value if it exists
    if variable_name in local_scope:
        return local_scope[variable_name]
    
    return None

